"""Location-based model chains (system.md §6.3, #188).

`resolve_auto_chain(lat, lon)` picks the region containing the point
(highest priority, then smallest area) from `graupel/models/regions.json`
(generated by `dev-tools/update_regions.py`). A region's chains are
preference lists: models whose domain does not cover the point with
`DOMAIN_MARGIN_DEG` are dropped, then every model that does not extend the
horizon by `MIN_EXTENSION_HOURS`. Without a region, or when only the
terminal model of the region's chain is left, the domain fallback takes
the regional models finer than `ecmwf_ifs` covering the point, finest
first, under the same rule, and ends with `ecmwf_ifs` / `ecmwf_ifs025`.
"""

import json
from functools import lru_cache
from typing import Any, Dict, List, Optional, Sequence, Tuple

from graupel.data.model_domains import (
    domain_contains,
    load_model_domains,
    point_in_ring,
)
from graupel.data.models import WeatherModel
from graupel.data.open_meteo import get_model_catalog
from graupel.resources import model_resource

REGIONS_FILENAME = "regions.json"
MAIN_TERMINAL = "ecmwf_ifs"
CLOUD_TERMINAL = "ecmwf_ifs025"
# Points closer than this to a domain edge count as outside.
DOMAIN_MARGIN_DEG = 0.5
# The fallback only uses regional models finer than the terminal model.
FALLBACK_MAX_RESOLUTION_KM = 9.0
# Blends and statistical products are never chosen automatically.
# HRDPS West: experimental, retired by ECCC in favour of HRDPS (2.5 km).
FALLBACK_EXCLUDED = {"best_match", "ncep_nbm_conus", "cmc_gem_hrdps_west"}
MIN_CLOUD_PRESSURE_LEVELS = 10
# A model joins a chain only when it extends the horizon by this much;
# shorter steps (DMI 59 h, then KNMI 60 h) add a model for nothing.
MIN_EXTENSION_HOURS = 12

Ring = Sequence[Tuple[float, float]]


@lru_cache(maxsize=1)
def load_regions() -> List[Dict[str, Any]]:
    """Regions sorted by priority (desc), then area (asc)."""
    with model_resource(REGIONS_FILENAME).open("r", encoding="utf-8") as f:
        features = json.load(f)["features"]
    regions = []
    for feature in features:
        props = dict(feature["properties"])
        props["polygons"] = [
            [[(x, y) for x, y in ring] for ring in poly]
            for poly in feature["geometry"]["coordinates"]
        ]
        # Bounding boxes skip the ray casting for far-away polygons; the
        # coastal waters made the outlines long enough to matter.
        props["boxes"] = [_bounds(rings[0]) for rings in props["polygons"]]
        props["box"] = _merge_bounds(props["boxes"])
        regions.append(props)
    regions.sort(key=lambda r: (-r["priority"], r["area_km2"]))
    return regions


Bounds = Tuple[float, float, float, float]


def _bounds(ring: Ring) -> Bounds:
    xs = [x for x, _ in ring]
    ys = [y for _, y in ring]
    return (min(xs), min(ys), max(xs), max(ys))


def _merge_bounds(boxes: List[Bounds]) -> Bounds:
    if not boxes:
        return (0.0, 0.0, -1.0, -1.0)  # contains nothing
    return (
        min(b[0] for b in boxes),
        min(b[1] for b in boxes),
        max(b[2] for b in boxes),
        max(b[3] for b in boxes),
    )


def _in_box(lon: float, lat: float, box: Bounds) -> bool:
    return box[0] <= lon <= box[2] and box[1] <= lat <= box[3]


def _in_multipolygon(
    lon: float,
    lat: float,
    polygons: List[List[Ring]],
    boxes: Optional[List[Bounds]] = None,
) -> bool:
    for i, rings in enumerate(polygons):
        if boxes is not None and not _in_box(lon, lat, boxes[i]):
            continue
        if point_in_ring(lon, lat, rings[0]) and not any(
            point_in_ring(lon, lat, hole) for hole in rings[1:]
        ):
            return True
    return False


# Simplified region outlines lose up to ~1 km along coasts and borders with
# countries without a region; a point there still takes a region this near.
REGION_SNAP_DEG = 0.02


def _region_containing(lat: float, lon: float) -> Optional[Dict[str, Any]]:
    for region in load_regions():
        if _in_box(lon, lat, region["box"]) and _in_multipolygon(
            lon, lat, region["polygons"], region["boxes"]
        ):
            return region
    return None


def region_at(lat: float, lon: float) -> Optional[Dict[str, Any]]:
    """The winning region at the point, or None.

    Without a region at the point itself, the eight points REGION_SNAP_DEG
    around it decide (highest priority, then smallest area).
    """
    region = _region_containing(lat, lon)
    if region is not None:
        return region
    nearby = [
        _region_containing(
            lat + dy * REGION_SNAP_DEG, lon + dx * REGION_SNAP_DEG
        )
        for dx in (-1, 0, 1)
        for dy in (-1, 0, 1)
        if dx or dy
    ]
    found = [r for r in nearby if r is not None]
    if not found:
        return None
    return min(found, key=lambda r: (-r["priority"], r["area_km2"]))


@lru_cache(maxsize=1)
def _catalogue() -> Dict[str, WeatherModel]:
    return {m.id: m for m in get_model_catalog() if m.id}


def _resolution_km(model: WeatherModel) -> Optional[float]:
    return model.spatial_resolution_km or model.spatial_resolution


def _cloud_capable(model: WeatherModel) -> bool:
    return bool(model.supports_vertical_cloud_profile) and (
        len(model.pressure_levels_hpa or []) >= MIN_CLOUD_PRESSURE_LEVELS
    )


def _covers(model_id: str, lat: float, lon: float) -> bool:
    return bool(domain_contains(model_id, lat, lon, DOMAIN_MARGIN_DEG))


def _filter(ids: Sequence[str], lat: float, lon: float) -> List[str]:
    """Covering models that extend the horizon, in preference order."""
    return _extending([m for m in ids if _covers(m, lat, lon)])


def _fallback_candidates(lat: float, lon: float, cloud: bool) -> List[str]:
    catalogue = _catalogue()
    candidates = []
    for model_id, domain in load_model_domains().items():
        model = catalogue.get(model_id)
        if (
            model is None
            or domain == "global"
            or "seamless" in model_id
            or "ensemble" in model_id
            or model_id in FALLBACK_EXCLUDED
            or (_resolution_km(model) or FALLBACK_MAX_RESOLUTION_KM)
            >= FALLBACK_MAX_RESOLUTION_KM
            or (cloud and not _cloud_capable(model))
            or not _covers(model_id, lat, lon)
        ):
            continue
        candidates.append(model)
    # Finest first; within one resolution the longest horizon first, so
    # each resolution tier contributes at most its longest model.
    candidates.sort(
        key=lambda m: (_resolution_km(m), -m.max_forecast_horizon_hours)
    )
    return [m.id for m in candidates if m.id]


def _extending(ids: Sequence[str]) -> List[str]:
    """Catalogue models that extend the horizon, in preference order."""
    catalogue = _catalogue()
    chain: List[str] = []
    horizon = 0
    for model_id in ids:
        model = catalogue.get(model_id)
        if model is None:
            continue
        if model.max_forecast_horizon_hours >= horizon + MIN_EXTENSION_HOURS:
            chain.append(model_id)
            horizon = model.max_forecast_horizon_hours
    return chain


def _with_terminal(chain: List[str], terminal: str) -> List[str]:
    chain = [m for m in chain if m != terminal]
    horizon = _catalogue()[terminal].max_forecast_horizon_hours
    while chain and (
        _catalogue()[chain[-1]].max_forecast_horizon_hours
        > horizon - MIN_EXTENSION_HOURS
    ):
        chain.pop()
    return chain + [terminal]


def _models(ids: List[str]) -> List[WeatherModel]:
    return [_catalogue()[m].model_copy() for m in ids]


def resolve_auto_chain(
    lat: float, lon: float, elevation: Optional[float] = None
) -> Dict[str, Any]:
    """Main and cloud chain for a location.

    Returns `main_model_chain` / `cloud_model_chain` (catalogue models with
    their catalogue horizons, strictly increasing), `region_id`,
    `region_name` and `resolution_reason` (`region`, `domain_fallback`,
    `global_fallback`). `elevation` is reserved for regions with elevation
    bounds (none in 0.2.0).
    """
    try:
        lat, lon = float(lat), float(lon)
        if not (-90 <= lat <= 90) or lon != lon:
            raise ValueError
    except (TypeError, ValueError):
        return _result(
            [MAIN_TERMINAL], [CLOUD_TERMINAL], None, "global_fallback"
        )
    lon = ((lon + 180) % 360) - 180

    region = region_at(lat, lon)
    fallback_main = _filter(_fallback_candidates(lat, lon, False), lat, lon)
    fallback_cloud = _filter(_fallback_candidates(lat, lon, True), lat, lon)
    if region is not None:
        main = _filter(region["main_chain_ids"], lat, lon)
        cloud = _filter(region["cloud_chain_ids"], lat, lon)
        # A region whose regional models all miss the point (only the
        # terminal model left) yields to a domain fallback with regional
        # models, e.g. overseas parts of a country.
        regional_left = any(m != MAIN_TERMINAL for m in main)
        if regional_left or not fallback_main:
            return _result(
                _with_terminal(main, MAIN_TERMINAL),
                _with_terminal(cloud, CLOUD_TERMINAL),
                region,
                "region",
            )
    reason = "domain_fallback" if fallback_main else "global_fallback"
    return _result(
        _with_terminal(fallback_main, MAIN_TERMINAL),
        _with_terminal(fallback_cloud, CLOUD_TERMINAL),
        None,
        reason,
    )


def _result(
    main: List[str],
    cloud: List[str],
    region: Optional[Dict[str, Any]],
    reason: str,
) -> Dict[str, Any]:
    return {
        "main_model_chain": _models(main),
        "cloud_model_chain": _models(cloud),
        "region_id": region["id"] if region else None,
        "region_name": region["name"] if region else None,
        "resolution_reason": reason,
    }


def list_regions() -> List[Dict[str, Any]]:
    """Regions without geometry, sorted by priority and area."""
    return [
        {k: v for k, v in r.items() if k not in ("polygons", "boxes", "box")}
        for r in load_regions()
    ]


def region_chains(region_id: str) -> Optional[Dict[str, Any]]:
    """A region's chains without a point (power mode, system.md §6.5).

    Same shape as `resolve_auto_chain`; only the horizon rule applies, so
    the whole preference list stays (e.g. USA HRRR → RDPS → NBM → IFS).
    None for an unknown region.
    """
    region = next((r for r in load_regions() if r["id"] == region_id), None)
    if region is None:
        return None
    return _result(
        _with_terminal(_extending(region["main_chain_ids"]), MAIN_TERMINAL),
        _with_terminal(_extending(region["cloud_chain_ids"]), CLOUD_TERMINAL),
        region,
        "region",
    )


# --- Chain zones (#198) ---------------------------------------------------

CHAIN_ZONES_FILENAME = "chain_zones.json"
# Dropdown groups (frontend order: regions, then these).
ZONE_GROUP_INTERCONTINENTAL = "Intercontinental"
ZONE_GROUP_GLOBAL = "Global"


@lru_cache(maxsize=1)
def load_chain_zones() -> List[Dict[str, Any]]:
    """Areas with one resolved chain (`dev-tools/update_regions.py`).

    The viewer's Chains tab draws the same zones (`docs/domain/chains.js`);
    this copy has no geometry.
    """
    with model_resource(CHAIN_ZONES_FILENAME).open("r", encoding="utf-8") as f:
        return json.load(f)["zones"]


def _chain_label(ids: Sequence[str]) -> str:
    catalogue = _catalogue()
    return " → ".join(
        (catalogue[m].short_name or catalogue[m].name)
        if m in catalogue
        else m
        for m in ids
    )


def _zone_origin(zone: Dict[str, Any]) -> str:
    """Where the resolver picks the chain, e.g. "USA" or "regional models"."""
    origin = (
        ", ".join(zone["regions"])
        if zone["regions"] and "domain_fallback" not in zone["reasons"]
        else "regional models"
        if "domain_fallback" in zone["reasons"]
        else "rest of the world"
    )
    if zone["group"] == ZONE_GROUP_GLOBAL:
        origin = "rest of the world"
    if not zone["area_km2"]:
        origin += " (at sea)"
    return origin


def list_auto_chains() -> List[Dict[str, Any]]:
    """Resolved chains that are not a region's own chain (#198).

    A region chain filtered by coverage (e.g. USA → RDPS only in southern
    Alaska), the domain fallback and the global fallback are picked at many
    places but have no region entry. Same shape as `resolve_auto_chain`
    plus `id`, `group`, `name` (chain short names), `origin` and
    `regions`; largest area first.
    """
    region_keys = set()
    for region in load_regions():
        result = region_chains(region["id"])
        if result is not None:
            region_keys.add(
                (
                    tuple(m.id for m in result["main_model_chain"]),
                    tuple(m.id for m in result["cloud_model_chain"]),
                )
            )
    catalogue = _catalogue()
    entries = []
    for zone in load_chain_zones():
        key = (tuple(zone["main_chain_ids"]), tuple(zone["cloud_chain_ids"]))
        if key in region_keys:
            continue
        if any(m not in catalogue for m in key[0] + key[1]):
            continue
        name = _chain_label(zone["main_chain_ids"])
        reason = (
            "global_fallback"
            if zone["group"] == ZONE_GROUP_GLOBAL
            else "domain_fallback"
            if "domain_fallback" in zone["reasons"]
            else "region"
        )
        entries.append(
            {
                **_result(
                    list(zone["main_chain_ids"]),
                    list(zone["cloud_chain_ids"]),
                    None,
                    reason,
                ),
                "id": zone["id"],
                "group": zone["group"],
                "name": name,
                "region_name": name,
                "origin": _zone_origin(zone),
                "regions": list(zone["regions"]),
                "area_km2": zone["area_km2"]
                + zone["coast_area_km2"]
                + zone["sea_area_km2"],
            }
        )
    entries.sort(key=lambda e: -e["area_km2"])
    return entries
