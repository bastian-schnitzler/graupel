"""Model domains: where a catalogue model delivers forecast data (system.md §6.2).

`graupel/models/model_domains.json` is generated by
`dev-tools/update_model_domains.py`. Each catalogue model maps to `"global"`
or to `{"source": "grid" | "measured", "polygon": [[lon, lat], ...]}`.
Polygons are not wrapped at the antimeridian (longitudes may leave
[-180, 180]) and a domain containing the pole is closed over it, so tests
shift the point by ±360° instead of splitting polygons.
"""

import json
from functools import lru_cache
from typing import Dict, List, Optional, Sequence, Tuple, Union

from graupel.resources import model_resource

DOMAINS_FILENAME = "model_domains.json"

Polygon = List[Tuple[float, float]]
Domain = Union[str, Polygon]


@lru_cache(maxsize=1)
def load_model_domains() -> Dict[str, Domain]:
    """Return every model's domain: `"global"` or a closed lon/lat ring."""
    with model_resource(DOMAINS_FILENAME).open("r", encoding="utf-8") as f:
        raw = json.load(f)
    domains: Dict[str, Domain] = {}
    for model_id, entry in raw["models"].items():
        if entry == "global":
            domains[model_id] = "global"
        else:
            domains[model_id] = [(lon, lat) for lon, lat in entry["polygon"]]
    return domains


def point_in_ring(
    lon: float, lat: float, ring: Sequence[Tuple[float, float]]
) -> bool:
    """Even-odd ray casting on lon/lat (no GIS dependency)."""
    inside = False
    n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]
        x2, y2 = ring[(i + 1) % n]
        if (y1 > lat) != (y2 > lat):
            x = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if x > lon:
                inside = not inside
    return inside


def _in_polygon(lon: float, lat: float, ring: Polygon) -> bool:
    return any(
        point_in_ring(lon + shift, lat, ring) for shift in (0.0, 360.0, -360.0)
    )


def domain_contains(
    model_id: str, lat: float, lon: float, margin_deg: float = 0.0
) -> Optional[bool]:
    """True when the model delivers data at the point.

    With `margin_deg`, the point and the eight points `margin_deg` around it
    must all lie inside, which keeps points away from the domain edge.
    Returns None for a model without a known domain.
    """
    domain = load_model_domains().get((model_id or "").lower())
    if domain is None:
        return None
    if isinstance(domain, str):  # "global"
        return True
    offsets = [(0.0, 0.0)]
    if margin_deg > 0:
        offsets += [
            (dx * margin_deg, dy * margin_deg)
            for dx in (-1, 0, 1)
            for dy in (-1, 0, 1)
            if dx or dy
        ]
    return all(
        _in_polygon(lon + dx, max(-90.0, min(90.0, lat + dy)), domain)
        for dx, dy in offsets
    )
